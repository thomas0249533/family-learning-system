def _check_essay_points(exercises, pkg_id):
    """essay 得分点必须能被 essayGrade 真正用上。

    - 至少 3 个得分点：阈值 0.6 时 2 个点要全中（太严），3 个点中 2 个才合理；
    - 每个 `/` 备选 ≥2 字：内核 `pointCovered` 会过滤单字备选，
      写「先/再/然后」里的「先」「再」等于白写，必须在数据侧就拦掉。
    """
    problems = []
    for ex in exercises:
        if ex["type"] != "essay":
            continue
        pts = ex.get("keyPoints") or []
        if len(pts) < 3:
            problems.append(f"{pkg_id}/{ex['id']}: 只有 {len(pts)} 个得分点（至少 3 个，否则阈值 0.6 判分过严）")
        for p in pts:
            for alt in p.replace("／", "/").split("/"):
                alt = alt.strip()
                if len(alt) < 2:
                    problems.append(f"{pkg_id}/{ex['id']}: 得分点备选「{alt}」不足 2 字，内核会忽略它")
    return problems


def build(grade: int, kps, units, pkg_id, title, path: Path):
    all_ex = []
    for u in units:
        topics = []
        for t in u["topics"]:
            exs = t["exercises"]
            all_ex.extend(exs)
            kp_ids = sorted({k for e in exs for k in e["knowledgePointIds"]})
            topics.append({
                "id": t["id"],
                "title": t["title"],
                "desc": t["desc"],
                "board": t["board"],
                "knowledgePointIds": kp_ids,
                "modules": [
                    {
                        "id": m[0],
                        "type": m[1],
                        "title": m[2],
                        "knowledgePointIds": m[3],
                    }
                    for m in u["modules"]
                ],
                "exercises": exs,
            })
        units_out = {
            "id": u["id"],
            "name": u["name"],
            "title": u["title"],
            "desc": u["desc"],
            "topics": topics,
        }
        u["_out"] = units_out

    pkg = {
        "manifest": {
            "schemaVersion": "1.0",
            "packageId": pkg_id,
            "type": "special",
            "packageType": "special",
            "isInternal": False,
            # ⚠️ 刻意**不**开 examMode（与 kantu 包一致），别"修正"成 True：
            #    QuizEngine 的 feedback-box / 音效都挂 `!examMode` 门禁。
            #    口语交际的价值在"说完立刻知道漏了哪个点"，开考试模式就只剩交卷后统一判，
            #    essay 的得分点提示（missing 清单）等于白做。
            "examMode": False,
            "subject": "chinese",
            "templateId": "chinese.primary.v1",
            "grade": grade,
            "term": "up",
            "edition": "人教版",
            "title": title,
            "dependencies": [],
        },
        "knowledgePoints": kps,
        "exercises": [],
        "units": [u["_out"] for u in units],
    }

    # 唯一性
    ids = [e["id"] for e in all_ex]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit(f"{pkg_id}: 题目 id 重复 {sorted(dup)}")
    kp_ids = [k["id"] for k in kps]
    if len(kp_ids) != len(set(kp_ids)):
        raise SystemExit(f"{pkg_id}: 知识点 id 重复")
    referenced = {k for e in all_ex for k in e["knowledgePointIds"]}
    unknown = referenced - set(kp_ids)
    if unknown:
        raise SystemExit(f"{pkg_id}: 题目引用了不存在的知识点 {sorted(unknown)}")

    problems = _check_essay_points(all_ex, pkg_id)
    if problems:
        raise SystemExit("得分点自检失败：\n  " + "\n  ".join(problems))

    from collections import Counter
    stat = Counter(e["type"] for e in all_ex)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(pkg, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"✓ {path.name}  {len(all_ex)} 题  " + "  ".join(f"{k}={v}" for k, v in sorted(stat.items())))
    for u in units:
        n = sum(len(t["exercises"]) for t in u["topics"])
        print(f"    {u['id']} {u['name']}: {n} 题")
    return stat


def main() -> int:
    b = build(
        2, KP2, UNITS2,
        "special-chinese-2-up-oral",
        "二上语文 · 口语交际专项（4 个话题）",
        ROOT / "content" / "chinese-2-up-rjb" / "special-chinese-2-up-oral.json",
    )
    f = build(
        4, KP4, UNITS4,
        "special-chinese-4-up-oral",
        "四上语文 · 口语交际专项（4 个话题）",
        ROOT / "content" / "chinese-4-up-rjb" / "special-chinese-4-up-oral.json",
    )
    total = sum(b.values()) + sum(f.values())
    print(f"\n合计 {total} 题")
    return 0


if __name__ == "__main__":
    sys.exit(main())
