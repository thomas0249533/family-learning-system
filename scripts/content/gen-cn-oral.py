"""
生成「口语交际」专项包（二上 / 四上，人教版）。

## 为什么这样设计题型

口语交际原卷是「大量开放填空 + 写话」，没有唯一答案，直接搬进系统会被判错。
本脚本按「能判分的才是好题」重排：

- 交际要求 / 得体性 / 表达方法 → single / multiple / judge（答案唯一，精确判分）
- 制作步骤、资料分类、做法与要求对应 → matching（左短标签 + 右句，索引配对）
- 真正要"说出来"的表达 → essay + 显式 keyPoints（要素族，`/` 列同义备选）

essay 判分依赖 @core/quiz/essayGrade：覆盖度 ≥0.6 判对。因此**每题至少 3 个得分点**
（3 点要中 2，4 点要中 3），且每个备选 ≥2 字（内核会过滤单字备选）。
本脚本的 `_check_essay_points` 会强制校验这两条，任何一条不满足直接报错退出。

用法：
    python scripts/content/gen-cn-oral.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

DIFF_BASIC = "基础"
DIFF_MID = "进阶"
DIFF_HARD = "挑战"

# 主观题的统一落款：口语交际的本质是"开口说"，系统只能收文字，
# 所以题干里固定要求先大声说给家长听，再写下来。
SAY_FIRST = "（先大声说给家长听，再写下来）"


def single(qid, question, options, answer, explanation, kp, diff=DIFF_BASIC, title=None):
    return {
        "id": qid,
        "type": "single",
        "question": question,
        "options": options,
        "answer": answer,
        "explanation": explanation,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, **({"title": title} if title else {})},
    }


def multiple(qid, question, options, answer, explanation, kp, diff=DIFF_MID, title=None):
    return {
        "id": qid,
        "type": "multiple",
        "question": question,
        "options": options,
        "answer": answer,
        "explanation": explanation,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, **({"title": title} if title else {})},
    }


def judge(qid, question, answer, explanation, kp, diff=DIFF_BASIC, title=None):
    return {
        "id": qid,
        "type": "judge",
        "question": question,
        "answer": answer,
        "explanation": explanation,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, **({"title": title} if title else {})},
    }


def matching(qid, question, left, right, answer, explanation, kp, diff=DIFF_MID, title=None):
    assert len(answer) == len(left), f"{qid}: answer 长度应等于 left 长度"
    assert all(0 <= i < len(right) for i in answer), f"{qid}: answer 索引越界"
    return {
        "id": qid,
        "type": "matching",
        "question": question,
        "left": left,
        "right": right,
        "answer": answer,
        "explanation": explanation,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, **({"title": title} if title else {})},
    }


def blank(qid, question, answer, explanation, kp, diff=DIFF_BASIC, title=None):
    return {
        "id": qid,
        "type": "blank",
        "question": question,
        "answer": answer,
        "explanation": explanation,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, **({"title": title} if title else {})},
    }


def essay(qid, question, answer, key_points, explanation, kp, diff=DIFF_MID, title=None):
    return {
        "id": qid,
        "type": "essay",
        "question": question,
        "answer": answer,
        "keyPoints": key_points,
        "explanation": explanation,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, **({"title": title} if title else {})},
    }


