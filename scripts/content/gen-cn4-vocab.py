def tone_of(word: str, table: dict[str, str]) -> str:
    """取词的拼音：人工纠正 > 教材标注 > 轻声修正表 > pypinyin 生成。"""
    if word in PINYIN_FIX:
        return PINYIN_FIX[word]
    if word in table:
        return table[word]
    if word in NEUTRAL_TONE:
        return NEUTRAL_TONE[word]
    return " ".join(x[0] for x in pinyin(word, style=Style.TONE))


def blank(qid, question, answer, explanation, kp, diff="基础", title=None):
    return {
        "id": qid,
        "type": "blank",
        "question": question,
        "answer": answer,
        "explanation": explanation,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, **({"title": title} if title else {})},
    }


