# 小工具：把"算出来的数"变成题干与答案，避免题干/答案各写一遍
# ---------------------------------------------------------------------------
def num(x) -> str:
    """把 Fraction/float/int 统一成中文教材里的小数写法（去掉末尾 0）。"""
    if isinstance(x, Fraction):
        if x.denominator == 1:
            return str(x.numerator)
        d = Fraction(x)
        s = f"{float(d):.6f}".rstrip("0").rstrip(".")
        return s
    if isinstance(x, float):
        return f"{x:.6f}".rstrip("0").rstrip(".")
    return str(x)


def blank(qid, question, answer, expl, kp, diff="基础", ability="运算能力"):
    return {
        "id": qid,
        "type": "blank",
        "question": question,
        "answer": answer if isinstance(answer, str) else num(answer),
        "explanation": expl,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, "ability": ability},
    }


def single(qid, question, options, answer, expl, kp, diff="基础", ability="运算能力"):
    return {
        "id": qid,
        "type": "single",
        "question": question,
        "options": options,
        "answer": answer,
        "explanation": expl,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, "ability": ability},
    }


def judge(qid, question, answer, expl, kp, diff="基础", ability="推理能力"):
    """answer 只能是「对」或「错」——与既有包一致（见 chinese-2-up-rjb 口语交际包）。"""
    assert answer in ("对", "错")
    return {
        "id": qid,
        "type": "judge",
        "question": question,
        "answer": answer,
        "explanation": expl,
        "knowledgePointIds": [kp],
        "metadata": {"difficulty": diff, "ability": ability},
    }


